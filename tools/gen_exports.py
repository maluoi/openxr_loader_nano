#!/usr/bin/env python3
# Generates the loader's dispatch table, exported trampolines, and export lists
# from xr.xml. Only needs re-running when a new core OpenXR version adds functions.
#
# Usage: python3 tools/gen_exports.py [path/to/xr.xml]
# Without a path, it downloads xr.xml for the release the vendored headers come from.

import os
import re
import sys
import urllib.request
import xml.etree.ElementTree as ET

ROOT    = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "src")
XML_URL = "https://raw.githubusercontent.com/KhronosGroup/OpenXR-SDK/release-{version}/specification/registry/xr.xml"

def vendored_version():
	with open(os.path.join(ROOT, "include", "openxr", "openxr.h"), encoding="utf-8") as f:
		match = re.search(r"define XR_CURRENT_API_VERSION XR_MAKE_VERSION\((\d+), *(\d+), *(\d+)\)", f.read())
	return ".".join(match.groups())

# Core functions the loader implements by hand instead of trampolining.
MANUAL = {
	"xrGetInstanceProcAddr",
	"xrEnumerateApiLayerProperties",
	"xrEnumerateInstanceExtensionProperties",
	"xrCreateInstance",
	"xrDestroyInstance",
}

# Extension functions the loader needs in its dispatch table, but doesn't export.
DISPATCH_EXTRA = [
	"xrCreateDebugUtilsMessengerEXT",
	"xrDestroyDebugUtilsMessengerEXT",
	"xrSetDebugUtilsObjectNameEXT",
	"xrSubmitDebugUtilsMessageEXT",
	"xrSessionBeginDebugUtilsLabelRegionEXT",
	"xrSessionEndDebugUtilsLabelRegionEXT",
	"xrSessionInsertDebugUtilsLabelEXT",
]

HEADER = "// Generated by tools/gen_exports.py from xr.xml, do not edit.\n"

def text_of(elem):
	return re.sub(r"\s+", " ", "".join(elem.itertext())).strip()

def main():
	if len(sys.argv) > 1:
		registry = ET.parse(sys.argv[1]).getroot()
	else:
		url = XML_URL.format(version=vendored_version())
		print(f"Downloading {url}")
		with urllib.request.urlopen(url) as response:
			registry = ET.fromstring(response.read())

	commands = {}
	for cmd in registry.iter("command"):
		proto = cmd.find("proto")
		if proto is None:
			continue
		name   = proto.find("name").text
		params = [text_of(p) for p in cmd.findall("param")]
		args   = [p.find("name").text for p in cmd.findall("param")]
		commands[name] = (text_of(proto.find("type")), params, args)

	core = []
	for feature in registry.iter("feature"):
		if not re.fullmatch(r"XR_VERSION_\d+_\d+", feature.get("name", "")):
			continue
		for req in feature.iter("require"):
			for cmd in req.iter("command"):
				if cmd.get("name") not in core:
					core.append(cmd.get("name"))

	exported   = core
	trampoline = [c for c in core if c not in MANUAL]
	dispatch   = trampoline + DISPATCH_EXTRA

	# Header: dispatch indices
	h = [HEADER, "#pragma once\n\n", "typedef enum xrl_fn_ {\n"]
	for name in dispatch:
		h.append(f"\txrl_fn_{name},\n")
	h.append("\txrl_fn_count,\n} xrl_fn_;\n\n")
	h.append("extern PFN_xrVoidFunction xrl_dispatch[xrl_fn_count];\n")
	h.append("extern const char        xrl_fn_names[];\n")
	write("exports.gen.h", "".join(h))

	# Source: names blob and trampolines
	c = [HEADER, '#include "loader.h"\n\n']
	c.append("PFN_xrVoidFunction xrl_dispatch[xrl_fn_count];\n\n")
	c.append("// Packed, in xrl_fn_ order\nconst char xrl_fn_names[] =\n")
	for name in dispatch:
		c.append(f'\t"{name}\\0"\n')
	c.append("\t;\n")
	for name in trampoline:
		ret, params, args = commands[name]
		assert ret == "XrResult", name
		c.append(f"\nXRL_EXPORT XRAPI_ATTR XrResult XRAPI_CALL {name}({', '.join(params)}) {{\n")
		c.append(f"\tPFN_{name} fn = (PFN_{name})xrl_dispatch[xrl_fn_{name}];\n")
		c.append(f"\treturn fn ? fn({', '.join(args)}) : xrl_dispatch_missing(xrl_fn_{name});\n")
		c.append("}\n")
	write("exports.gen.c", "".join(c))

	# Export lists for shared builds
	write("openxr_loader.def", "EXPORTS\n" +"".join(f"\t{n}\n" for n in exported))
	write("openxr_loader.map", "{\n\tglobal:\n" + "".join(f"\t\t{n};\n" for n in exported) + "\tlocal:\n\t\t*;\n};\n")
	write("openxr_loader.expsym", "".join(f"_{n}\n" for n in exported))

	print(f"{len(exported)} exports, {len(trampoline)} trampolines, {len(dispatch)} dispatch entries")

def write(name, text):
	with open(os.path.join(OUT_DIR, name), "w", newline="\n") as f:
		f.write(text)

if __name__ == "__main__":
	main()
